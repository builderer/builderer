def switches_for(switches: List[Switch], toolset: str) -> List[Switch]:
    return [s for s in switches if toolset in TOOLSET_SWITCHES.get(s[:2], {toolset})]


# Set the property of each recognized flag and return the other flags in order.
def map_flags(
    properties: Dict[str, str], flags: List[str], switches: List[Switch]
) -> List[str]:
    remaining: List[str] = []
    i = 0
    while i < len(flags):
        flag = flags[i]
        i += 1
        name = "/" + flag[1:] if flag.startswith("-") else flag
        matched = False
        for switch, prop, value, arg in switches:
            if arg & Arg.FOLLOWING:
                if name != switch or i >= len(flags):
                    continue
                user = flags[i]
                i += 1
            elif arg & Arg.VALUE:
                if not name.startswith(switch):
                    continue
                user = name[len(switch) :]
                if not user and not arg & Arg.IGNORED:
                    continue
            elif name == switch or (
                arg & Arg.CASE_INSENSITIVE and name.upper() == switch.upper()
            ):
                user = ""
            else:
                continue
            new = user if value is None else value
            if arg & Arg.LIST and properties.get(prop):
                new = f"{properties[prop]};{new}"
            properties[prop] = new
            matched = True
            if not arg & Arg.CONTINUE:
                break
        if not matched:
            remaining.append(flag)
    return remaining

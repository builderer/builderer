# MSBuild properties that correspond to cl.exe and link.exe switches.
#
# A recognized switch is removed from AdditionalOptions and set as its property
# instead. The tables are Visual Studio's own switch definitions as CMake
# extracts them, plus /std:c++23 and the "/D name" and "/I dir" forms CMake also
# accepts. They are matched the way CMake matches them: a switch may start with
# '-' or '/'; entries are tried in order; a fixed switch matches exactly; a VALUE
# switch matches by prefix and takes the rest as its value (optional when the
# value is IGNORED); a FOLLOWING switch takes the next argument; LIST properties
# accumulate with ';'; and a CONTINUE entry lets later entries match the same
# switch.

from enum import Flag
from typing import Dict, List, Optional, Tuple


class Arg(Flag):
    FIXED = 0
    VALUE = 1  # the switch is followed by the user's value: /wd4100
    FOLLOWING = 2  # the user's value is the next argument: /FI x.h
    IGNORED = 4  # the value is optional and the property gets the entry's value
    CONTINUE = 8  # later entries may also match the switch
    LIST = 16  # values accumulate, separated by ';'
    CASE_INSENSITIVE = 32


Switch = Tuple[str, str, Optional[str], Arg]

